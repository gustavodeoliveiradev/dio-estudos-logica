// Operadores de Atribuição
// 1. Atribuição Simples (=)
// 2. Atribuição de Adição (+=)
// 3. Atribuição de Subtração (-=)
// 4. Atribuição de Multiplicação (*=)
// 5. Atribuição de Divisão (/=)
// 6. Atribuição de Módulo (%=)

// Exemplo 1. Atribuição Simples:
let nome = "João";
console.log("operação de atribuição simples: " + nome);
// Atribuição Simples é quando atribuimos um valor a uma variável usando o sinal de igual (=).

// Exemplo 2. Atribuição de Adição:
let numero = 10;
numero += 5;
console.log("operação de atribuição de adição: " + numero);
// Atribuição de Adição é quando atribuimos um valor a uma variável usando o sinal de igual e o operador de adição (+=).

// Exemplo 3. Atribuição de Subtração:
let valor = 20;
valor -= 3;
console.log("operação de atribuição de subtração: " + valor);
// Atribuição de Subtração é quando atribuimos um valor a uma variável usando o sinal de igual e o operador de subtração (-=).

// Exemplo 4. Atribuição de Multiplicação:
let preco = 50;
preco *= 2;
console.log("operação de atribuição de multiplicação: " + preco);
// Atribuição de Multiplicação é quando atribuimos um valor a uma variável usando o sinal de igual e o operador de multiplicação (*=).

// Exemplo 5. Atribuição de Divisão:
let total = 100;
total /= 4;
console.log("operação de atribuição de divisão: " + total);
// Atribuição de Divisão é quando atribuimos um valor a uma variável usando o sinal de igual e o operador de divisão (/=).

// Exemplo 6. Atribuição de Módulo:
let resto = 15;
resto %= 4;
console.log("operação de atribuição de módulo: " + resto);
// Atribuição de Módulo é quando atribuimos um valor a uma variável usando o sinal de igual e o operador de módulo (%=).