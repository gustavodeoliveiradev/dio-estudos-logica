// Operadores Aritméticos
// 1. Adição (+)
// 2. Subtração (-)
// 3. Multiplicação (*)
// 4. Divisão (/)
// 5. Módulo (%)

// Exemplo 1. Adição:
let idade = 30;
idade = 30 + 6;
console.log("operação de adição: " + idade);
// podemos fazer a mesma operação de maneiras diferentes, como por exemplo:
let numero1 = 30;
let numero2 = 4;
let resultado = numero1 + numero2;
console.log("operação de adição: " + resultado);

// Exemplo 2. Subtração:
let codigoDoProduto = 1023;
let codigoExato = codigoDoProduto - 1000;
console.log("operação de subtração: " + codigoExato);
// podemos fazer a mesma operação de maneiras diferentes, como por exemplo:
let primeiroNumero = 1032;
let segundoNumero = 1000;
console.log("operação de subtração: " + (primeiroNumero - segundoNumero));

// Exemplo 3. Multiplicação:
let precoProduto = 100.99;
let valorComTaxa = precoProduto * 2;
console.log("operação de multiplicação: " + valorComTaxa);
// podemos fazer a mesma operação de maneiras diferentes, como por exemplo:
let multiplicador = 4;
let multiplicando = 12;
let produto = multiplicador * multiplicando;
console.log("operação de multiplicação: " + produto);

// Exemplo 4. Divisão:
let notaDoMercado = 50;
console.log("operação de divisão: " + notaDoMercado / 2);
// podemos fazer a mesma operação de maneiras diferentes, como por exemplo:
let valorTotal = 100;
let pessoasParaDividir = 5;
let valorPorPessoa = valorTotal / pessoasParaDividir;
console.log("operação de divisão: " + valorPorPessoa);

// Exemplo 5. Módulo:
let calculo = 10 % 3;
console.log("operação de módulo: " + calculo);
// podemos fazer a mesma operação de maneiras diferentes, como por exemplo:
let dividendo = 15;
let divisor = 4;
let resto = dividendo % divisor;
console.log("operação de módulo: " + resto);