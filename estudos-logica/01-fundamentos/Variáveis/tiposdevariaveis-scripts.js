// pokemon
let nomePokemon = "Pikachu";
let pokemonSexo = "M";

let nivelPokemon = 20;
let pontosDeVidaPokemon = 45;

let selecionavel = true;

/* O JavaScript é uma linguagem não tipada, 
ou seja, não é necessário declarar o tipo da variável como em outras linguagens de programação. 
O JavaScript irá inferir o tipo a partir do valor atribuído a ela. 
Exemplos: nomePokemon é uma string, nivelPokemon é um number e selecionavel é um boolean.

 Tipos de variáveis primitivos e mais comuns de encontrar em JavaScript:
 string: são variáveis que armazenam texto. Exemplo: nomePokemon e pokemonSexo.
 number: são variáveis que armazenam números. Exemplo: nivelPokemon, pontosDeVidaPokemon
 boolean: são variáveis lógicas que armazenam valores verdadeiro ou falso. Exemplo: selecionavel */

 /* Variáveis numéricas (number): Usadas para guardar números.
 - Inteiros (int) - Armazenam números inteiros, como 1, 10, -5.
 - Ponto flutuante ou decimal (float) - Armazenam números com casas decimais, como 3.14, -0.5.
 - Números complexos (complex) - Armazenam números complexos, como 2+3j. */

 /* Variáveis de texto (strings): Usadas para guardar  sequência de caracteres 
 - String - Armazena uma sequência de caracteres, como "Olá, mundo!" 
 - Caractere - Armazena um único caractere, como 'a', 'X', '@'. */ 

 /* Variáveis lógicas (boolean): Usadas para guardar valores do tipo verdadeiro ou falso.
 - Boolean - Armazena os valores True ou False. */

 /* Variáveis de data e hora: Usadas para guardar datas e horários.
 - Data - Armazena datas, no formato AAAA-MM-DD.
 - Hora - Armazena horários, no formato HH:MM:SS. */